export type Params = unknown[];

export interface Queryable {
  all<T = Record<string, unknown>>(sql: string, ...params: Params): Promise<T[]>;
  one<T = Record<string, unknown>>(sql: string, ...params: Params): Promise<T | undefined>;
  /** Returns the number of rows changed. */
  run(sql: string, ...params: Params): Promise<number>;
}

export interface Db extends Queryable {
  tx<T>(fn: (q: Queryable) => Promise<T>): Promise<T>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
  kind: "postgres" | "pglite";
}

/** `?` → `$n`, skipping quoted strings. */
export function toPg(sql: string): string {
  let n = 0;
  let out = "";
  let quote: string | null = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
      out += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === "?") {
      out += `$${++n}`;
    } else {
      out += ch;
    }
  }
  return out;
}

// undefined is not a valid parameter; booleans are stored as 0/1 like before.
const norm = (params: Params) => params.map((p) => (p === undefined ? null : typeof p === "boolean" ? (p ? 1 : 0) : p));

/**
 * Connections per instance. Queries take about 2 ms on the server, so this is plenty — and
 * src/lib/db.ts never lets more than this many queries be in flight at once, because handing a
 * queue of them to the driver at the same time hangs against Supabase's transaction pooler.
 */
export const POOL_MAX = 4;

async function openPostgres(url: string): Promise<Db> {
  const { default: postgres } = await import("postgres");
  const toNumber = { to: 20, from: [20, 1700], serialize: (x: unknown) => String(x), parse: (x: string) => Number(x) };
  const make = () =>
    postgres(url, {
      prepare: false, // Supabase transaction pooler
      max: POOL_MAX,
      idle_timeout: 10,
      // Let a connection go after a few minutes even when it is busy, rather than keeping one that
      // the database may have given up on.
      max_lifetime: 60 * 5,
      // Fail fast instead of leaving a page hanging until the function's time limit.
      connect_timeout: 10,
      connection: { application_name: "onside" },
      onnotice: () => {},
      types: { num: toNumber },
    });
  // The first connection out of a cold instance sometimes never answers. Prove it with a query of
  // our own rather than letting the first page wait on it.
  const sql = await firstContact(make);
  type Unsafe = { unsafe: (q: string, p?: never[]) => Promise<unknown[] & { count: number }> };
  const wrap = (s: Unsafe): Queryable => ({
    all: async <T,>(q: string, ...p: Params) => (await s.unsafe(toPg(q), norm(p) as never[])) as unknown as T[],
    one: async <T,>(q: string, ...p: Params) => ((await s.unsafe(toPg(q), norm(p) as never[])) as unknown as T[])[0],
    run: async (q: string, ...p: Params) => (await s.unsafe(toPg(q), norm(p) as never[])).count ?? 0,
  });
  const base = wrap(sql as unknown as Unsafe);
  return {
    ...base,
    kind: "postgres",
    tx: (fn) => sql.begin((t) => fn(wrap(t as unknown as Unsafe))) as never,
    exec: async (q) => {
      await sql.unsafe(q);
    },
    close: () => sql.end(),
  };
}

// One try, kept short: db() forgets a pool that fails to open, so the next request opens another,
// and every query has a deadline of its own (src/lib/db.ts) for connections that die later.
const FIRST_CONTACT_MS = 6000;
const FIRST_CONTACT_TRIES = 1;

type Sql = { unsafe: (q: string) => Promise<unknown>; end: (o?: { timeout?: number }) => Promise<void> };

/** Opens a client and proves it answers, with a fresh client on each retry. */
async function firstContact<T extends Sql>(make: () => T): Promise<T> {
  let last = "";
  for (let attempt = 1; attempt <= FIRST_CONTACT_TRIES; attempt++) {
    const sql = make();
    let timer: ReturnType<typeof setTimeout> | undefined;
    try {
      await Promise.race([
        sql.unsafe("SELECT 1"),
        new Promise<never>((_, reject) => {
          timer = setTimeout(() => reject(new Error(`no answer within ${FIRST_CONTACT_MS / 1000}s`)), FIRST_CONTACT_MS);
        }),
      ]);
      return sql;
    } catch (e) {
      last = e instanceof Error ? e.message : String(e);
      console.error(`database: attempt ${attempt} of ${FIRST_CONTACT_TRIES} failed (${last})`);
      void sql.end({ timeout: 1 }).catch(() => {});
    } finally {
      clearTimeout(timer);
    }
  }
  throw new Error(`Could not reach the database after ${FIRST_CONTACT_TRIES} tries: ${last}`);
}

/**
 * The local database is a directory only one process may write to. Two at once corrupt it, so
 * hold a lock file while it is open and say plainly what to stop.
 */
function lockLocalDb(dir: string) {
  const lock = path.join(dir, "in-use.pid");
  try {
    const pid = Number(fs.readFileSync(lock, "utf8"));
    if (pid && pid !== process.pid) {
      process.kill(pid, 0); // throws when that process has gone
      throw new Error(
        `The local database is already open (process ${pid}). Stop \`npm run dev:local\` first, then run this again.`,
      );
    }
  } catch (e) {
    if (e instanceof Error && e.message.startsWith("The local database is already open")) throw e;
    // no lock file, or the process in it has gone: carry on
  }
  fs.writeFileSync(lock, String(process.pid));
  const drop = () => fs.rmSync(lock, { force: true });
  process.once("exit", drop);
  process.once("SIGINT", () => {
    drop();
    process.exit(130);
  });
  process.once("SIGTERM", () => {
    drop();
    process.exit(143);
  });
}

async function openPglite(dir: string): Promise<Db> {
  const { PGlite } = await import("@electric-sql/pglite");
  fs.mkdirSync(dir, { recursive: true });
  lockLocalDb(dir);
  const pg = await PGlite.create(dir, { parsers: { 20: (x: string) => Number(x), 1700: (x: string) => Number(x) } });
  type Pq = { query: <T>(q: string, p?: unknown[]) => Promise<{ rows: T[]; affectedRows?: number }> };
  const wrap = (s: Pq): Queryable => ({
    all: async <T,>(q: string, ...p: Params) => (await s.query<T>(toPg(q), norm(p))).rows,
    one: async <T,>(q: string, ...p: Params) => (await s.query<T>(toPg(q), norm(p))).rows[0],
    run: async (q: string, ...p: Params) => (await s.query(toPg(q), norm(p))).affectedRows ?? 0,
  });
  // PGlite runs one query at a time; chain transactions so they never interleave.
  let chain: Promise<unknown> = Promise.resolve();
  const base = wrap(pg as unknown as Pq);
  return {
    ...base,
    kind: "pglite",
    tx: (fn) => {
      const next = chain.then(() => pg.transaction((t) => fn(wrap(t as unknown as Pq))));
      chain = next.catch(() => {});
      return next;
    },
    exec: async (q) => {
      await pg.exec(q);
    },
    close: () => pg.close(),
  };
}

export async function openDb(opts: { url?: string; migrate?: boolean; local?: boolean } = {}): Promise<Db> {
  // ONSIDE_DB=local keeps this computer on PGlite even when DATABASE_URL is set (tests, trying things out).
  const url = opts.local ? undefined : (opts.url ?? (process.env.ONSIDE_DB === "local" ? undefined : process.env.DATABASE_URL));
  const db = url ? await openPostgres(url) : await openPglite(PGLITE_DIR);
  // Local databases set themselves up; Supabase is set up with `npm run db:setup`.
  if (opts.migrate ?? db.kind === "pglite") {
    await db.exec(SCHEMA);
    await db.exec(ADDED_COLUMNS);
  }
  return db;
}

export const json = {
  parse<T>(value: string | null | undefined, fallback: T): T {
    if (!value) return fallback;
    try {
      return JSON.parse(value) as T;
    } catch {
      return fallback;
    }
  },
};
